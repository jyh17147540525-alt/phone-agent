def build(kind, texts, srcmap):
    out=[]
    for t in texts:
        h="am-"+hashlib.sha1(t.encode()).hexdigest()[:20]
        out.append({"id":h,"kind":kind,"text":t,
                    "src":[],"conf":0.93,"at":srcmap})
    return out

# 时间：短条目按"最近"处理（用原库最大时间），日结论用各自时间段
maxt=max(r['at'] for r in rows)
out=[]
for d in sorted(DAYS):
    g=[x for x in rows if x['kind']=='STAGE_CONCLUSION' and day(x['at'])==d]
    if not g: continue
    out.append({"id":"am-"+hashlib.sha1((d+DAYS[d]).encode()).hexdigest()[:20],
        "kind":"STAGE_CONCLUSION","text":DAYS[d],"src":[],"conf":0.93,
        "at":min(x['at'] for x in g)})
out += build("CONSTRAINT", C, maxt)
out += build("PREFERENCE", P, maxt)
out += build("FACT", F, maxt)

old_c=sum(len(r['text']) for r in rows); new_c=sum(len(r['text']) for r in out)
print(f"条数: {len(rows)} → {len(out)}")
