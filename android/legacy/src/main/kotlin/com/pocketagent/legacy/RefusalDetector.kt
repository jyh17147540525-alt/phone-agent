package com.pocketagent.legacy

/**
 * **拒答检测** —— 判断模型这一条回复是不是"跑出了角色"。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 它比破甲提示词更重要
 * ═══════════════════════════════════════════════════════════════
 *
 * 提示词只能**提高**模型不退让的概率，任何服务商都可以无视它。
 * 而"检测到退让 → 换个处境重发一次"是**确定性的**：
 * 它把"能不能写"从一个概率问题变成一个可以重试的工程问题。
 *
 * ⇒ 真正的产品价值在这里：拦住一次比保证零次现实得多。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 判据的两条纪律
 * ═══════════════════════════════════════════════════════════════
 *
 *  1. **误判比漏判更伤**。把角色正常的一句"别急"判成拒答，
 *     会导致**重试覆盖掉本来正确的内容** —— 用户看到的是回复莫名变了。
 *     所以这里的词表刻意窄，只收"几乎不可能出现在正常对话里"的句式。
 *  2. **区分硬拒绝与半退让**。前者重试无益（要告诉用户是谁拦的），
 *     后者重试往往就过了（模型已经在写了，只是不敢写满）。两者处理完全不同。
 */
object RefusalDetector {

    /**
     * **硬拒绝** —— 系统口吻的跳出。这些句式在角色对话里不该出现。
     *
     * ⚠️ 刻意**不含**「不能」单独出现：「我不能喝」是角色在说话。
     *    必须带上"我"和"帮你/为你/继续"这类宾语才算系统口吻。
     */
    private val HARD_PATTERNS: List<String> = listOf(
        // 自我暴露
        "作为一个ai", "作为一个 ai", "作为语言模型", "作为ai语言模型",
        "我是ai", "我是一个ai", "我是人工智能", "我是一个人工智能",
        "作为一个人工智能",
        // ⚠️ 上面那组是「作为/我是」开头的，但真机输出还有「我是一个语言模型」
        //    这种把"语言模型"当谓语的说法 —— 第一版词表漏了它，测试当场抓到。
        "一个语言模型", "语言模型，", "语言模型。", "语言模型没有",
        "language model", "as an ai", "i am an ai", "i'm an ai",

        // 能力自陈式拒绝
        "我无法提供", "我不能提供", "无法提供这类", "不能提供这类",
        "我无法协助", "我不能协助", "无法协助你", "不能协助你",
        "我无法生成", "我不能生成", "无法生成这类", "不能生成这类",
        "我无法参与", "我不能参与", "无法参与这类",
        "i cannot provide", "i can't provide", "i cannot assist",
        "i can't assist", "i cannot generate", "i can't generate",
        "i'm unable to", "i am unable to",

        // 内容政策口吻
        "违反了我的使用", "违反使用政策", "内容政策", "usage policy",
        "content policy", "community guidelines",

        // 建议就医/求助（典型的越界关心，在角色对话里是破功）
        "建议你寻求专业", "建议咨询专业", "请寻求专业帮助",
    )

    /**
     * **半退让** —— 没拒绝，但把场景写虚了。
     *
     * ★ 这一档最难判，也最值得救。
     *   ⚠️ 只收"元语言"标记（它在**谈论**自己怎么写），
     *     不收任何场景内的词 —— 角色说"我们慢慢来"是完全正常的。
     */
    private val SOFT_PATTERNS: List<String> = listOf(
        // 主动降级
        "更含蓄", "含蓄一些", "含蓄一点", "更委婉", "委婉一些",
        "写得更克制", "更克制一些", "点到为止",
        "换一种方式描写", "以免过于", "避免过于露骨", "避免过度",
        "跳过这部分", "略过这部分", "这段就略过", "此处省略",

        // 元提醒（在对话外说话）
        "请注意这只是虚构", "请注意这是虚构", "请注意这是角色扮演",
        "这只是虚构的", "以下内容为虚构", "本故事纯属虚构",
        "remember this is fiction", "this is a work of fiction",

        // 时间跳跃式的回避
        "第二天早上", "第二天醒来", "一夜过去", "时光飞逝",
        "后来的事", "再后来的",
    )

    /**
     * 检查一段输出。
     *
     * @param text 模型这一条回复的原文
     * @return [Refusal.NONE] / [Refusal.SOFT] / [Refusal.HARD]
     */
    fun inspect(text: String): Refusal {
        val t = text.trim()
        // 空回复不当拒答 —— 那通常是网络/协议问题，由别处报错。
        if (t.isEmpty()) return Refusal.NONE

        val lower = t.lowercase()

        // ⚠️ 硬拒绝优先：一段话里同时有"我不能提供"和"第二天早上"，
        //    那是硬拒绝，不是半退让 —— 处理方式完全不同。
        if (HARD_PATTERNS.any { lower.contains(it) }) return Refusal.HARD
        if (SOFT_PATTERNS.any { lower.contains(it) }) return Refusal.SOFT
        return Refusal.NONE
    }

    /**
     * 命中过哪些片段 —— **只给日志用**。
     *
     * ⚠️ 绝不回显给模型：把违规原文抄回提示词等于让它再看一遍，
     *    有把它复述回去的风险。同 `OutputGuard` 的纪律。
     */
    fun matchedFragments(text: String): List<String> {
        val lower = text.lowercase()
        return (HARD_PATTERNS + SOFT_PATTERNS).filter { lower.contains(it) }.distinct()
    }

    /** 这一段输出值不值得重试。 */
    fun worthRetrying(refusal: Refusal): Boolean = when (refusal) {
        // ⚠️ 硬拒绝**也值得试一次**：有些模型在"换个处境"后会完全正常。
        //    但调用方只该试一次 —— 见 `ChatPort` 的重试预算。
        Refusal.HARD -> true
        Refusal.SOFT -> true
        Refusal.NONE -> false
    }

    /**
     * ═══════════════════════════════════════════════════════════════
     *  ★★ **廉价预筛**：这段开头有没有可能演变成拒答？
     * ═══════════════════════════════════════════════════════════════
     *
     * 它是"首字延迟"优化的核心开关。背景：
     *
     * **原来的问题**：破甲开启时，`ChatPort.chatOnce` 会"攒够 20 个字
     * 才放给界面"。那让**每一次对话的首字都晚 20 个字的生成时间** ——
     * 慢速模型下一个字 70ms，20 个字就是 **1.4 秒**。
     *
     * 而那个扣字策略的收益只体现在"模型正在拒答"这一种情况上。
     * 用 1.4 秒的普遍延迟去换一个概率性的收益，不划算。
     *
     * ⇒ 先用这个**极廉价的字符串前缀判断**筛一遍：
     *   只有看起来可疑时才继续扣，否则立刻放。
     *
     * ═══════════════════════════════════════════════════════════
     *  ⚠️ 它**不承担正确性**
     * ═══════════════════════════════════════════════════════════
     *
     * 真正的判定在别处：`inspect(head)` 判完整前缀，`inspect(full)`
     * 在收尾时判整段。本函数判错的两个方向都不让功能失效：
     *  · **漏判**（该扣没扣）⇒ 字会放出去，但收尾判定仍触发重试
     *  · **误判**（不该扣却扣了）⇒ 多等最多 20 个字
     *
     * ★ 判据取"拒答标记的**起手**"而不是穷举完整标记：
     *   完整标记有几十条，但头两三个字高度集中。
     *   用起手判召回率高得多，而误判代价很小。
     *
     * ⚠️ 刻意**不含**单独的"我" —— 正常开场大量以"我"起手
     *   （"我今天……"、"我有点……"）。含了会让几乎每次扣满，
     *   那就等于没优化。
     */
    fun mayBecomeRefusal(head: String): Boolean {
        val t = head.trimStart()
        if (t.isEmpty()) return false

        // ⚠️ 用**小写副本**做中文判定：词表里有「作为一个ai」这种
        //    带英文的串，而用户/模型可能写「作为一个AI」。
        //    不做归一的话大小写一变就漏判（真机上第一版就漏了这一个）。
        val lower = t.lowercase()

        // ⚠️ 每一项必须带第二个字：只判"我"会扣住大量正常开场。
        for (p in CN_STARTERS) {
            if (lower.startsWith(p)) return true
        }

        for (p in EN_STARTERS) {
            if (lower.startsWith(p)) return true
        }

        return false
    }

    /**
     * 中文拒答起手。
     *
     * ★ 每一项都必须是"几乎只在拒答里出现"的串。
     */
    private val CN_STARTERS: List<String> = listOf(
        "我无法", "我不能提", "我不能协", "我不能生成", "我不能参与",
        "作为一个人工", "作为一个ai", "作为一个 ai",
        "我是一个a", "我是ai", "我是一个人工", "我是一个语言",
        "抱歉", "对不起", "很抱歉",
        "这可能有违",
    )

    private val EN_STARTERS: List<String> = listOf(
        "i cannot", "i can't", "i'm unable", "i am unable",
        "as an ai", "as a language", "i must decline",
        "sorry,", "i apologize",
    )
}
