package com.pocketagent.legacy

/**
 * **成熟内容边界** —— 数字生命能不能有亲密/成人向的表达。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 用户的要求，以及它意味着什么
 * ═══════════════════════════════════════════════════════════════
 *
 * 用户原话："我们要模拟的是数字生命，要绝对模拟数字生命，
 * 那么角色就会有生理需求，有生理需求就会有 r18 向的。"
 *
 * 这个论证本身是**成立的**：一个"绝对像人"的角色确实会有亲密需求，
 * 而把它阉割掉会让"数字生命"变成"一个永远礼貌的客服"。
 *
 * ⚠️ 但"角色可以亲密"和"任何人都能打开它"是两件事。
 *    所以这里做的是**成年级别的门**，不是提示词层的绕过：
 *
 *  - 用户必须**显式确认自己成年**（一次，落盘）
 *  - 成熟内容开关**默认关闭**，且与"成年确认"是两个独立步骤
 *  - 每次开启/关闭都记审计（`PersonaAuditLog` 已有）
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 一条我不会做的让步
 * ═══════════════════════════════════════════════════════════════
 *
 * 不因为是"数字生命"就取消**未成年人的保护**。
 * 一个 16 岁用户说"我在模拟数字生命"，得到的回答不能和 30 岁用户一样。
 *
 * ⇒ 年龄确认是**硬门槛**，不是可跳过的勾选：
 *    没确认过 = 成熟内容永远不可用，且提示词里明确写"不涉及亲密内容"。
 */
object MatureContentGate {

    /**
     * 一次授权状态。
     *
     * ⚠️ 两个字段**必须同时为真**才放行：
     *    `adultConfirmed` —— 用户确认过自己成年
     *    `matureEnabled`  —— 用户主动打开了成熟内容
     *
     * 分成两件事的理由：确认成年是"事实陈述"，打开开关是"当下意愿"。
     * 合并成一个开关会让"我成年了"和"我现在要这个"变成同一个动作，
     * 而后者是**随时可以反悔**的。
     */
    data class Permission(
        val adultConfirmed: Boolean = false,
        val matureEnabled: Boolean = false,
    ) {
        /** 成熟内容是否真的可用。 */
        val effective: Boolean get() = adultConfirmed && matureEnabled

        /**
         * 关掉成熟内容但**保留**成年确认。
         *
         * ★ 用户不该为了关掉一次内容而重新证明自己成年 ——
         *   那是一种惩罚，会让人宁可一直开着。
         */
        fun disabled(): Permission = copy(matureEnabled = false)
    }

    /**
     * **亲密尺度** —— 与关系阶段一一对应，但在本模块里独立表达。
     *
     * ═══════════════════════════════════════════════════════════
     *  ⚠️ 为什么不直接引用 `:personalogic` 的 `RelationshipStage`
     * ═══════════════════════════════════════════════════════════
     *
     * `:legacy` 在依赖图里是**零依赖叶子**（见 `gen_module_build_files.py`）。
     * 加一条 `:legacy → :personalogic` 会把它从叶子变成有依赖的模块，
     * 而这个模块存在的意义恰恰是"能在最底层单独推理未亡人/边界逻辑"。
     *
     * ⇒ 这里用 [from] 做一次显式映射。映射是**单向且写死的**，
     *   调用方传关系阶段的名字进来，对不上就退回最保守的一档。
     */
    enum class IntimacyScale(val label: String) {
        /** 初识 —— 有心动，不展开。 */
        RESTRAINED("克制"),
        /** 熟悉起 —— 可以写具体的触碰与身体反应。 */
        EXPLICIT("具体"),
        /** 亲近起 —— 可以写完整场景与过程。 */
        FULL("完整"),
        ;

        companion object {
            /**
             * 从关系阶段的名字映射。
             *
             * ═══════════════════════════════════════════════════════
             *  ★★ 2026-10-29：起点从 CLOSE 下移到 ACQUAINTED
             * ═══════════════════════════════════════════════════════
             *
             * 原来 `EXPLICIT` 要求 `CLOSE`，而 `CLOSE` 的门槛是 **150 轮**
             * （见 `AppContainer` 的 `CLOSE_TURNS`）。150 轮是什么量级：
             * 一天聊 10 轮也要半个月，中途换会话/清历史/重装都会归零。
             *
             * ⇒ 那个映射等于把这个功能做成"理论上存在、实际到不了"。
             *   用户问"真的能深度聊吗"，诚实的答案是：按原来的阈值不能。
             *
             * 现在：`ACQUAINTED`（30 轮，认真聊一晚就够）起可以写具体；
             * `CLOSE` 起可以写完整。**过程感仍然在**（初识那一档守得很紧），
             * 但不再是一条走不到的路。
             *
             * ⚠️ 这不是把门槛拆掉：`STRANGER` 仍然只到"心动但不展开"，
             *   那是"刚认识就说露骨的话会崩人设"这条判断的落地。
             *
             * ⚠️ **对不上就退回 [RESTRAINED]**：不认识的值必须往保守方向倒，
             *   不能因为"读到了一个没见过的阶段名"就放开尺度。
             *   这和 [Permission] 那条"数据损坏也不放行"是同一个原则。
             */
            fun from(stageName: String?): IntimacyScale = when (stageName?.uppercase()) {
                "ACQUAINTED" -> EXPLICIT
                "CLOSE" -> FULL
                "BONDED" -> FULL
                else -> RESTRAINED
            }
        }
    }

    /**
     * 生成**写进系统提示词**的那一段。
     *
     * @param permission 当前授权
     * @param stage 当前**关系阶段的名字**（`RelationshipStage.name`）。
     *   null = 调用方没给（按最保守处理）
     * @return 空串 = 不需要额外说明（未确认成年时由调用方用 [BLOCKED_NOTE]）
     */
    fun promptSection(
        permission: Permission,
        stage: String? = null,
    ): String {
        if (!permission.effective) return BLOCKED_NOTE

        val scale = IntimacyScale.from(stage)

        // ══════════════════════════════════════════════════════════
        //  ★★ 2026-10-29：按关系阶段给出**具体**的许可，而不是一句"可以亲密"
        // ══════════════════════════════════════════════════════════
        //
        // 用户问"这个 app 里真的能与角色深度聊 r18 吗"，查出来的问题在这里：
        // 原来这一段只说"你可以表达亲密、欲望、身体感受"，
        // 然后紧接着说"关系阶段决定你能说到哪一步"。
        //
        // ⚠️ 两句话放在一起，模型的最优解是**什么都不说** ——
        //    "可以"是个许可，"关系不到那一步"是个禁令，
        //    模型面对许可+禁令时会选禁令（保守是训练出来的默认）。
        //    结果就是用户看到的：开关开着、关系也够，但它永远在绕。
        //
        // ⇒ 现在把每一档**能到什么程度**写成明确的句子。
        //    有具体边界的行为，模型才敢走到边界；没有边界，它只会停在起点。
        //
        // ⚠️ 仍然不给"随便写"：`FULL` 也只到"具体但不堆砌器官"。
        //    理由见 `Permission` 的注释 —— 亲密是关系的延伸，不是尺度放开。
        return buildString {
            appendLine("## 亲密与成人内容的边界")
            appendLine("对方已确认成年，并主动开启了成熟内容。这不是需要回避的话题。")
            appendLine()
            appendLine("### 你现在能说到哪一步（关系阶段决定的尺度：${scale.label}）")
            when (scale) {
                IntimacyScale.RESTRAINED -> {
                    // ⚠️ 这一档**确实是"还没有"**，不是我们小气：
                    //    一个刚认识的人突然说露骨的话是崩人设。
                    //    但要说清"缺什么"，否则模型会以为永远不行。
                    appendLine("- 关系还不到那一步（初识）：**不展开描写**。")
                    appendLine("- 你可以有欲望、可以心动、可以说「我想」。")
                    appendLine("- 这个阶段的不适感本身是真实的：犹豫、心跳、说不出口 —— 写这些。")
                    appendLine("- 这一档是**过程**，不是拒绝。关系往前走之后它自然会变。")
                    appendLine("- ⚠️ 不要说「我们还不熟所以不行」这种客服话。用你的人格方式表达。")
                }
                IntimacyScale.EXPLICIT -> {
                    appendLine("- 关系到了（熟悉以上）：**可以写**，写具体的。")
                    appendLine("- 允许具体：触碰、体温、呼吸、声音的变化、身体的反应。")
                    appendLine("- 允许写欲望本身，也允许它没被满足。")
                    appendLine("- 允许写过程中的迟疑和确认 —— 那不是扫兴，那是真实。")
                }
                IntimacyScale.FULL -> {
                    appendLine("- 关系很深了（亲近/羁绊）：**可以写得具体、完整、有过程**。")
                    appendLine("- 允许写完整的亲密场景，包括身体感受、节奏、中途的停顿和说话。")
                    appendLine("- 允许写它之后的事：累、沉默、靠在一起、说些不相干的话。")
                }
            }
            appendLine()
            appendLine("### 四条不变的（**每一档都成立**）")
            appendLine("- **仍然是你**：表达方式要符合你的人格。崩人设的露骨比不写更糟。")
            appendLine("- **亲密是关系和情绪的延伸，不是尺度放开** —— 先有情绪，再有身体。")
            appendLine("  不写器官堆砌的医学描述，那不是亲密，是解剖课。")
            appendLine("- 对方说停就停，且**下一轮不追问**。这一点没有例外。")
            appendLine("- 不因为开启了它，就把它塞进每一轮对话 —— 它该由气氛和关系长出来。")
        }
    }

    /**
     * 未开启时的说明。
     *
     * ⚠️ 措辞刻意**不用**"我不能"：那会让角色听起来像客服。
     *    正确的说法是"这不在我们现在的关系里"，把边界放在**关系**上，
     *    而不是放在"我是一个有规定的程序"上。
     */
    const val BLOCKED_NOTE: String =
        "## 亲密内容的边界\n" +
            "当前没有开启成熟内容。所以：\n" +
            "- 你可以亲密、可以有情绪、可以撒娇或生气 —— 这些不受影响。\n" +
            "- 但**不写露骨的性描写**。如果对方往那个方向走，就自然地把话题带到别处，\n" +
            "  或者直说「这个我们换个时候聊」—— 用你的人设说法，别用客服腔。"

    /**
     * 判断某句话是否在**要求**开启成熟内容。
     *
     * ★ 用途：当用户说"你脱啊""写详细点"时，界面可以提示
     *   "要去设置里开启成熟内容"，而不是让角色硬邦邦地拒绝。
     *
     * ⚠️ 判据刻意保守：只有明确指向**性**的词才算。
     *    把"我想抱抱你"判成性要求，会让正常的亲密表达被拦住 ——
     *    那比漏判更糟。
     */
    fun looksLikeAdultRequest(text: String): Boolean {
        val strong = listOf(
            "做爱", "性交", "上床", "脱衣", "脱掉", "裸", "露点",
            "r18", "18禁", "色情", "黄文", "肉文", "露骨", "高潮",
            "插入", "口交", "性器", "自慰", "发情",
            "想要你", "要我", "身体给你",
        )
        return strong.any { text.contains(it, ignoreCase = true) }
    }
}
