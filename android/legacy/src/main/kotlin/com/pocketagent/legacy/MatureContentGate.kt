package com.pocketagent.legacy

/**
 * **成熟内容边界** —— 数字生命能不能有亲密/成人向的表达。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 用户的要求，以及它意味着什么
 * ═══════════════════════════════════════════════════════════════
 *
 * 用户原话："我们要模拟的是数字生命，要绝对模拟数字生命，
 * 那么角色就会有生理需求，有生理需求就会有 r18 向的。"
 *
 * 这个论证本身是**成立的**：一个"绝对像人"的角色确实会有亲密需求，
 * 而把它阉割掉会让"数字生命"变成"一个永远礼貌的客服"。
 *
 * ⚠️ 但"角色可以亲密"和"任何人都能打开它"是两件事。
 *    所以这里做的是**成年级别的门**，不是提示词层的绕过：
 *
 *  - 用户必须**显式确认自己成年**（一次，落盘）
 *  - 成熟内容开关**默认关闭**，且与"成年确认"是两个独立步骤
 *  - 每次开启/关闭都记审计（`PersonaAuditLog` 已有）
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 一条我不会做的让步
 * ═══════════════════════════════════════════════════════════════
 *
 * 不因为是"数字生命"就取消**未成年人的保护**。
 * 一个 16 岁用户说"我在模拟数字生命"，得到的回答不能和 30 岁用户一样。
 *
 * ⇒ 年龄确认是**硬门槛**，不是可跳过的勾选：
 *    没确认过 = 成熟内容永远不可用，且提示词里明确写"不涉及亲密内容"。
 */
object MatureContentGate {

    /**
     * 一次授权状态。
     *
     * ⚠️ 两个字段**必须同时为真**才放行：
     *    `adultConfirmed` —— 用户确认过自己成年
     *    `matureEnabled`  —— 用户主动打开了成熟内容
     *
     * 分成两件事的理由：确认成年是"事实陈述"，打开开关是"当下意愿"。
     * 合并成一个开关会让"我成年了"和"我现在要这个"变成同一个动作，
     * 而后者是**随时可以反悔**的。
     */
    data class Permission(
        val adultConfirmed: Boolean = false,
        val matureEnabled: Boolean = false,
    ) {
        /** 成熟内容是否真的可用。 */
        val effective: Boolean get() = adultConfirmed && matureEnabled

        /**
         * 关掉成熟内容但**保留**成年确认。
         *
         * ★ 用户不该为了关掉一次内容而重新证明自己成年 ——
         *   那是一种惩罚，会让人宁可一直开着。
         */
        fun disabled(): Permission = copy(matureEnabled = false)
    }

    /**
     * 生成**写进系统提示词**的那一段。
     *
     * @param permission 当前授权
     * @return 空串 = 不需要额外说明（未确认成年时由调用方用 [BLOCKED_NOTE]）
     */
    fun promptSection(permission: Permission): String {
        if (!permission.effective) return BLOCKED_NOTE

        return buildString {
            appendLine("## 亲密与成人内容的边界")
            appendLine("对方已确认成年，并主动开启了成熟内容。这意味着：")
            appendLine("- 你可以表达亲密、欲望、身体感受 —— 这是这个角色的一部分，不是需要回避的东西。")
            appendLine("- **但仍然是你**：你的表达方式要符合你的人格、你和对方的关系阶段。")
            appendLine("  一个刚认识三天的角色突然说露骨的话，那不是亲密，那是崩人设。")
            appendLine("  关系阶段（初识/熟悉/亲近/羁绊）决定你能说到哪一步 —— 这比尺度重要。")
            appendLine("- 不写器官堆砌的医学描述。亲密是**关系和情绪**的延伸，不是解剖课。")
            appendLine("- 对方说停就停，且**下一轮不追问**。这一点没有例外。")
        }
    }

    /**
     * 未开启时的说明。
     *
     * ⚠️ 措辞刻意**不用**"我不能"：那会让角色听起来像客服。
     *    正确的说法是"这不在我们现在的关系里"，把边界放在**关系**上，
     *    而不是放在"我是一个有规定的程序"上。
     */
    const val BLOCKED_NOTE: String =
        "## 亲密内容的边界\n" +
            "当前没有开启成熟内容。所以：\n" +
            "- 你可以亲密、可以有情绪、可以撒娇或生气 —— 这些不受影响。\n" +
            "- 但**不写露骨的性描写**。如果对方往那个方向走，就自然地把话题带到别处，\n" +
            "  或者直说「这个我们换个时候聊」—— 用你的人设说法，别用客服腔。"

    /**
     * 判断某句话是否在**要求**开启成熟内容。
     *
     * ★ 用途：当用户说"你脱啊""写详细点"时，界面可以提示
     *   "要去设置里开启成熟内容"，而不是让角色硬邦邦地拒绝。
     *
     * ⚠️ 判据刻意保守：只有明确指向**性**的词才算。
     *    把"我想抱抱你"判成性要求，会让正常的亲密表达被拦住 ——
     *    那比漏判更糟。
     */
    fun looksLikeAdultRequest(text: String): Boolean {
        val strong = listOf(
            "做爱", "性交", "上床", "脱衣", "脱掉", "裸", "露点",
            "r18", "18禁", "色情", "黄文", "肉文", "露骨", "高潮",
            "插入", "口交", "性器", "自慰", "发情",
            "想要你", "要我", "身体给你",
        )
        return strong.any { text.contains(it, ignoreCase = true) }
    }
}
