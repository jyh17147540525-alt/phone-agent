package com.pocketagent.capabilitylogic

/**
 * 一次能力调用请求。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ [confirmedByUser] **不是万能钥匙**
 * ═══════════════════════════════════════════════════════════════
 *
 * 最自然的写法是在裁决器开头加一句：
 *
 * ```kotlin
 * if (call.confirmedByUser) return Allowed(...)   // ✗ 危险
 * ```
 *
 * 它读起来很合理 —— 用户都点过确认了，还检查什么？
 *
 * **但那样一来，确认就变成了绕过一切的后门。** 而具体的路径很现实：
 * agent 先请求"关掉勿扰"（用户看了一眼，点了确认），然后在真正执行前
 * 把 `capabilityId` 换成"停用某个 App" —— 裁决器看到 `confirmedByUser = true`
 * 直接放行。第 3 步不需要恶意，它可以是模型的一次"修正"或一次重试。
 *
 * **用户确认的是他看到的那个操作，不是这个函数收到的那个操作。**
 *
 * 所以本模块的纪律与 `FileAccessDecider` 完全一致：
 * **硬拒绝清单、来源限制、参数校验在每一次裁决里都重新跑一遍**，
 * [confirmedByUser] 只是一个"如果结论是 RequireConfirmation，就降级为 Allowed"的开关。
 */
data class CapabilityCall(

    /** 见 [CapabilityCatalog] 里的 id */
    val capabilityId: String,

    /**
     * 参数。值一律是字符串 —— 因为它的**最终归宿是一段命令行**，
     * 提前转成 Int 只会让"参数非法"的报错点离真正出错的地方更远。
     *
     * ⚠️ 用 `Map` 而不是 `data class XxxArgs`：能力是**数据驱动**的，
     *    参数集合来自目录里的声明。写成强类型会让"新增一条能力"变成"改代码"，
     *    而这一步越轻，越不会有人为了省事去加一条通用能力。
     */
    val args: Map<String, String> = emptyMap(),

    /**
     * 谁发起的。
     *
     * ⚠️ 它**参与裁决**，不是纯粹的可观测字段：见 [CapabilityGuard] 步骤 2，
     *    插件发起的调用碰不到 [CapabilityRisk.GUARDED] 能力。
     */
    val origin: CallOrigin = CallOrigin.AGENT,

    /** 用户是否已就本次操作点过确认。见类注释 —— 它不改变任何前置判定。 */
    val confirmedByUser: Boolean = false,

    /**
     * 用户是否已就**这次操作会动到的那个文件**点过确认。
     *
     * ═══════════════════════════════════════════════════════════════
     *  ⚠️ 为什么它不能和 [confirmedByUser] 合并成一个
     * ═══════════════════════════════════════════════════════════════
     *
     * 两个闸问的是**两个不同的问题**：
     *
     * | 字段 | 问的是什么 | 用户看到的话 |
     * |---|---|---|
     * | [confirmedByUser] | 你允许 agent 做这类事吗 | 「要执行「把一段文字写进文件。**文件已经存在时，它的原内容会被替换掉**」。这一次具体是：写入 .../hello.txt（20 字）。」 |
     * | [operationConfirmedByUser] | 这一次要动的那个文件，你确定吗 | 「「hello.txt」**已经存在**（22 B）。继续写入会把它的原有内容「整体替换掉」，而且没法撤销。要覆盖它吗？」 |
     *
     * ★ 2026-09-23 真机实证：这两句话**不是同一件事**。差别比看上去细，但很关键：
     *
     *   · 能力闸那句风险提示是**条件式**的（"文件**已经存在时**……"），
     *     而且**没有说这一次到底存不存在**；后半句"写入 .../hello.txt（20 字）"
     *     读起来更像"新建一个小文件"。
     *   · 文件闸那句是**无条件的事实 + 证据**："已经存在（22 B）"。
     *
     *   ⇒ 用户在前一闸要**自己推断**"那它到底在不在"，在后一闸是被**告知**。
     *     要签掉"一个文件的内容会消失"这件事，用户该看到的是后者。
     *
     *   ⚠️ 更要紧的一点：能力闸那句来自 `Capability.summary`，是**静态文案** ——
     *     每次执行一字不差。而人对一成不变的话是会读过去的。
     *     文件闸那句每次都带当前事实（大小、修改时间），读不过去。
     *
     * 合并成一个标志的后果，真机上表现为：用户点掉第一闸之后，
     * 第二闸**根本不弹** —— `FileAccessDecider` 看到 `confirmedByUser = true`
     * 就放行了覆盖。于是"这个文件已存在、原内容会被替换"这句话
     * **永远没有机会出现在屏幕上**，而用户以为自己在新建文件。
     *
     * ⚠️ 所以两者必须**各自被用户单独答一次**。这不是"多问一次"的代价，
     *    而是"第二句话能不能被说出来"的前提。
     *
     * ⚠️ 默认值 false 是**安全侧**：忘了传的后果是"多问一次"，
     *    不是"没问就覆盖了"。
     */
    val operationConfirmedByUser: Boolean = false,
)

/**
 * 调用来源。
 *
 * ⚠️ **默认值是 [AGENT]，不是 [PLUGIN]。** 这个方向是刻意的：
 *    插件加载器必须**显式**声明来源，忘记传就退化成"用户自己发起"是不行的 ——
 *    那会让一个忘记传参的插件获得比预期更大的权限。
 *    而默认成 AGENT 时，忘记传参的插件会得到 AGENT 的权限……
 *
 *    ⇒ 所以真正的防线在 [CapabilityGuard] 里：**只有 [PLUGIN] 被特殊限制，
 *      其余来源一律按同等对待**。默认值选谁都不会放宽插件，
 *      但选 AGENT 能让"插件忘了传"这件事在审计日志里留下可疑痕迹
 *      （一条 `origin=AGENT` 但调用栈来自插件进程的记录）。
 */
enum class CallOrigin(
    val displayName: String,
) {
    /** 本体自己的 agent 循环 */
    AGENT("PocketAgent"),

    /** L1/L2/L3 插件。**碰不到 GUARDED 能力** */
    PLUGIN("插件"),

    /** 用户手动触发（快捷方式、界面上的按钮） */
    USER("你自己"),

    /**
     * 定时任务触发的调用。
     *
     * ⚠️ 与 [AGENT] 分开记，是因为它的**风险画像完全不同**：
     *    定时任务在无人值守时执行，此时"弹确认框问用户"这条护栏是失效的。
     *    所以它需要一套单独的夜间策略（预声明任务白名单），
     *    而审计日志要能回答"这条操作是凌晨自动做的还是白天有人看着做的"。
     */
    SCHEDULE("定时任务"),
}
