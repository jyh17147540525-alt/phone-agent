package com.pocketagent.agentui

/**
 * 风险等级。
 *
 * ★ 为什么风险由**工具声明**而不是由通道推导：
 *   同一次"点击"，在设置页是 [READ] 级别的影响，在支付页是 [MONEY] 级别。
 *   通道（无障碍/Shizuku/IME）只决定"怎么点"，不决定"点了会怎样"。
 *   把两者混在一起，就会出现"用 Shizuku 所以更危险"这种没有意义的判断。
 *
 * ★ 顺序有意义：[READ] 最低，[IDENTITY] 最高。`ordinal` 可直接比大小。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 仓库里另外两个风险枚举**不能**替代这一个（已核对，勿合并）
 * ═══════════════════════════════════════════════════════════════
 *
 * | 枚举 | 回答的问题 | 粒度 |
 * |---|---|---|
 * | `:plugin:api` 的 `PluginCapability.RiskLevel` | 「这个**插件**有多危险」（给用户看的标尺） | 低/中/高/极高 |
 * | `:capabilitylogic` 的 `CapabilityRisk` | 「这个能力要不要**逐项放行**」 | SAFE / GUARDED |
 * | 本枚举 | 「这一次**动作**会对用户的世界做什么」 | 读/写/外发/花钱/身份 |
 *
 * 差别的**要害**在最后两档：[MONEY] 与 [IDENTITY] 要求"永远只给这一次"
 * （见 [rememberable]），而"低/中/高/极高"与"SAFE/GUARDED"都表达不出
 * "这次可以，下次还得再问"。合并的直接后果是**付款流程会记住授权**。
 *
 * ⇒ 三者是**三个维度**，不是三份重复。`PluginCapability.RiskLevel` →
 *   本枚举的映射放在 `:app`（`:agentui` 不依赖 `:plugin:api`，这是它的
 *   零依赖约束），且映射**必然是多对一** —— 这正说明它们不等价。
 */
enum class RiskLevel {
    /** 只读：读屏、读文件、列目录。**不问用户**。 */
    READ,

    /** 写入本机：输入文字、改设置、建闹钟。问一次，记住。 */
    WRITE,

    /** 对外发送：发消息、发邮件、发朋友圈。每次都问（除非用户明确"以后都行"）。 */
    EXTERNAL,

    /** 花钱：下单、付款、充值。**永远只给"这一次"**。 */
    MONEY,

    /** 身份：实名信息、验证码、证件、密码。**永远只给"这一次"**。 */
    IDENTITY,
    ;

    /**
     * 能不能"以后都行"。
     *
     * ★ [MONEY] 与 [IDENTITY] 恒为 false —— 这不是保守，是"一次授权不该
     *   覆盖将来所有的付款"。用户说"以后都行"时，他自己也不知道
     *   下次会买什么、买多少。
     */
    val rememberable: Boolean
        get() = this != MONEY && this != IDENTITY

    /** 是否需要征得用户同意。 */
    val requiresConsent: Boolean
        get() = this != READ
}
