package com.pocketagent.agentui

/**
 * **转场语义** —— 这一跳该用哪种动画。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★★ 用户的原话："各个页面之间的切换有种突兀感"
 * ═══════════════════════════════════════════════════════════════
 *
 * 回查发现**不是曲线不够顺，是结构错了**：平级和层级用了同一种动画。
 *
 * ```
 *   任务 ──(横向滑动)──▶ 插件 ──(横向滑动)──▶ 设置
 *            ↑                    ↑
 *        这是平级互换          这也是平级互换
 * ```
 *
 * 横向滑动的语义是"进入下一层 / 返回上一层"。但底栏那三个是**平级**。
 * 用户的大脑会短暂以为自己在钻取，然后发现又回到了同一层 ——
 * 那种错位就是"突兀"的主要成分。
 *
 * ★ iOS 的 tab bar 切换**从不横向滑动**，只有交叉淡入（或干脆瞬切）。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 为什么这段要住在纯 Kotlin 里
 * ═══════════════════════════════════════════════════════════════
 *
 * 它原本是 `AppShell` 里的一个局部函数（依赖 NavBackStackEntry）——
 * 于是**进不了离线验证器**，只能靠真机手感判断对错。
 * 而这类判断一旦错了，症状是"感觉有点怪"，极难归因。
 *
 * ⇒ 剥成"给定起点路由与终点路由，返回该用哪种动画"的纯函数。
 *   本模块在验证器里，所以它可以被测。
 */
object TransitionKind {

    /** 这一跳该用哪种动画。 */
    enum class Kind {
        /**
         * **平级互换** —— 纯交叉淡入，**零位移、零缩放**。
         *
         * ⚠️ 位移的语义是"空间位置变了"。平级互换时空间没变，
         *    只是"这一层换成了另一层"。加位移会让大脑误判成钻取。
         */
        TAB_SWAP,

        /**
         * **向下钻取** —— 新页面从右侧微移进来。
         *
         * ★ 方向感在这里是**对的**：用户确实进了更深的一层，
         *   所以"从右边来"符合他的心理模型。
         */
        DRILL_IN,

        /**
         * **向上返回** —— 上一层从左侧深处浮回来。
         */
        DRILL_OUT,
    }

    /**
     * 判断这一跳该用哪种动画。
     *
     * @param fromRoute 起点路由（null = 首个页面，没有起点）
     * @param toRoute 终点路由
     * @param topLevel 顶层 tab 的集合
     * @param isPop 是否是一次返回（`popBackStack` / 系统返回键）
     */
    fun of(
        fromRoute: String?,
        toRoute: String?,
        topLevel: Set<String>,
        isPop: Boolean,
    ): Kind {
        // ⚠️ 两头都没有路由 = **没有转场**（理论上不会发生）。
        //    这里给 DRILL_IN 而不是 DRILL_OUT，理由是"进入"是个更中性的
        //    默认值：淡入 + 微位移在任何情况下都不会看起来破。
        //    而 DRILL_OUT 会让内容从左边浮进来 —— 那需要真的有一个"上一层"。
        if (fromRoute == null && toRoute == null) return Kind.DRILL_IN
        if (fromRoute == null) return Kind.DRILL_IN
        if (toRoute == null) return Kind.DRILL_OUT

        val fromTop = fromRoute in topLevel
        val toTop = toRoute in topLevel

        // ⚠️⚠️ 这一条是本类的核心，也是最容易写错的一条：
        //   **必须两头都在顶层才算平级互换。**
        //
        //   只判终点（`toTop`）的话：
        //     「设置 → 插件源」再点底栏「任务」
        //     起点是 sources（二级），终点是 tasks（顶层）——
        //     按"只判终点"会被判成平级互换 ⇒ 纯淡入。
        //     但用户这一步是**从深层回到顶层**，他期待"退回去"的方向感。
        //     砍掉位移会让这一跳失去方向，反而更突兀。
        if (fromTop && toTop) return Kind.TAB_SWAP

        return if (isPop) Kind.DRILL_OUT else Kind.DRILL_IN
    }

    /**
     * 是否**零位移**。
     *
     * ★ 单独暴露这个判断而非让调用方 `== TAB_SWAP`：
     *   将来若多出一种平级变体（比如"同级替换"），
     *   这里改一处，所有调用点自动正确。
     */
    fun isSpatial(kind: Kind): Boolean = kind != Kind.TAB_SWAP
}
