package com.pocketagent.agentui

/**
 * **图标尺寸与自适应图标几何** —— 设计规则的代码化。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★★ 2026-11-01：为什么需要这个
 * ═══════════════════════════════════════════════════════════════
 *
 * 上一轮我在拉条里写了 `.size(16.dp)` —— 随手挑的。
 * 而在同一个界面里，别处的图标是 20dp、24dp。
 * 三种尺寸并排出现时，用户说不出哪里不对，但会觉得"不齐"。
 *
 * ⇒ 图标尺寸必须像字号一样有**一套档位**，不能每次现挑。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 两组外部规范（查过来源，不是编的）
 * ═══════════════════════════════════════════════════════════════
 *
 * **一、Material 图标尺寸**
 * Material Design 的图标系统以 **24dp 为基准**，配 4dp 网格。
 * 常见档位是 16 / 20 / 24 / 32 / 40 / 48。
 * ⇒ 本文件把它收敛成 5 档，并强制**全部是 4 的倍数**：
 *    这样图标落在 4dp 网格上，与 8dp 间距体系天然对齐。
 *
 * **二、自适应图标安全区**（Android 官方）
 * 自适应图标的前景层画布是 **108dp × 108dp**，但：
 *  · 只有中心 **72dp 直径**（即约 66dp 见方）保证可见
 *  · 外层 18dp 会被各种厂商遮罩裁掉
 *  ⇒ 前景内容必须落在 **21dp ~ 87dp** 之间（108 减去两侧 21）。
 *
 * 本项目的 `ic_launcher_foreground.xml` 内容在 **30~78**（含 4dp 描边外扩），
 * 落在安全区内，合规。见 [isWithinSafeZone] 的测试。
 *
 * ⚠️ 这一层刻意做成**纯逻辑**：它不画图，只回答"这个尺寸/位置合不合规"。
 *    这样它能在离线验证器里被测到，而不是等到真机上肉眼发现。
 */
object IconGeometry {

    // ─────────────────────────────────────────────────────────────
    //  一、图标尺寸档位
    // ─────────────────────────────────────────────────────────────

    /**
     * 图标尺寸档位。
     *
     * ★ 每档的用途写死在名字里，避免"这个图标该多大"每次都靠感觉：
     *
     * | 档位 | dp | 用在哪 |
     * |---|---|---|
     * | [INLINE] | 16 | 与文字同行（拉条 chip、标签旁） |
     * | [COMPACT] | 20 | 列表项的行内图标 |
     * | [DEFAULT] | 24 | 顶栏、按钮、导航 —— Material 基准 |
     * | [PROMINENT] | 32 | 空状态、卡片主图标 |
     * | [HERO] | 48 | 引导页、大按钮 |
     */
    enum class Size(val dp: Int) {
        /** 与文字同行。最小可用尺寸 —— 再小就看不清了。 */
        INLINE(16),

        /** 列表项行内。 */
        COMPACT(20),

        /** **默认**。顶栏、按钮、导航 —— Material 的 24dp 基准。 */
        DEFAULT(24),

        /** 空状态、卡片主图标。 */
        PROMINENT(32),

        /** 引导页、大按钮。 */
        HERO(48),
        ;

        /**
         * 是否落在 4dp 网格上。
         *
         * ★ 这不是洁癖：图标与间距体系共用 4dp 网格，
         *   落在网格外的尺寸会让"图标 + 文字"的基线对不齐 ——
         *   而那种错位正是"看起来不精致"的来源。
         */
        val onGrid: Boolean get() = dp % GRID_DP == 0
    }

    /** 基础网格。Material 的图标与间距都以 4dp 为单位。 */
    const val GRID_DP: Int = 4

    /**
     * 找一个"最接近"的档位。
     *
     * ★ 给的是**域内收敛**而不是精确匹配：设计稿上偶尔会出现 18dp 这种值，
     *   它应该被拉回 20 而不是报错。报错会让人绕过这一层直接写死。
     */
    fun nearest(dp: Int): Size =
        Size.entries.minWithOrNull(
            // ⚠️ 第一键是距离；第二键是**负的 dp** —— 于是等距时大的优先。
            //
            // ★ 为什么等距要向上取：18 距 16 和 20 都是 2。
            //   取 16 会让图标偏小、与旁边 20dp 的图标不齐；
            //   取 20 至少"够大"，而"大一点"比"小一点"更不容易读不清。
            //
            // ⚠️ 这条不是可选的：不指定次序时 `minByOrNull` 取**先出现的**，
            //    而档位表一改（比如把 COMPACT 挪到 INLINE 前面），
            //    同样的 18 就会给出不同结果 —— 那是一个只在某些尺寸上复现的 bug。
            compareBy({ kotlin.math.abs(it.dp - dp) }, { -it.dp }),
        ) ?: Size.DEFAULT

    /** 这个尺寸在档位表里吗。用于测试与静态检查。 */
    fun isCanonical(dp: Int): Boolean = Size.entries.any { it.dp == dp }

    // ─────────────────────────────────────────────────────────────
    //  二、自适应图标安全区
    // ─────────────────────────────────────────────────────────────

    /** 自适应图标前景层的画布边长。Android 规定就是 108dp。 */
    const val ADAPTIVE_LAYER_DP: Int = 108

    /**
     * 安全区的内缩量。
     *
     * ★ 108 - 66 = 42，两侧各 21。
     * ⇒ 内容必须画在 **21..87** 之间。
     *
     * ⚠️ 另一种常见说法是"中心 72dp 直径圆"。两者不等价：
     *    66dp 见方是**保守**的那个。按保守的做，两种遮罩都不会裁到内容。
     */
    const val SAFE_INSET_DP: Double = 21.0

    /** 安全区的起止（含）。 */
    val SAFE_MIN_DP: Double get() = SAFE_INSET_DP
    val SAFE_MAX_DP: Double get() = ADAPTIVE_LAYER_DP - SAFE_INSET_DP

    /**
     * 这段内容（含描边外扩）是否落在安全区内。
     *
     * @param minCoord 内容最左/最上坐标（dp）
     * @param maxCoord 内容最右/最下坐标（dp）
     * @param strokeWidth 描边宽度（dp）。描边会**向外溢出半个宽度** ——
     *   ⚠️ 这个细节最容易漏：路径坐标在 21 上，4dp 描边实际画到 19，越界了。
     */
    fun isWithinSafeZone(
        minCoord: Double,
        maxCoord: Double,
        strokeWidth: Double = 0.0,
    ): Boolean {
        val out = strokeWidth / 2.0
        return minCoord - out >= SAFE_MIN_DP && maxCoord + out <= SAFE_MAX_DP
    }

    /**
     * 内容在画布上的占比。
     *
     * ★ 用来判断"图标看起来是不是太小"。自适应图标被遮罩后，
     *   可见区域只有 66dp —— 前景若只画了 30dp，用户看到的是一个
     *   小得可怜的图形，周围一圈空白。
     *
     * 经验区间：**0.5 ~ 0.85**。低于 0.5 显得空，高于 0.85 会被裁。
     */
    fun fillRatio(minCoord: Double, maxCoord: Double): Double {
        val content = maxCoord - minCoord
        return if (ADAPTIVE_LAYER_DP <= 0) 0.0 else content / ADAPTIVE_LAYER_DP
    }

    /**
     * 占比是否在建议区间内。
     *
     * ⚠️ 这是**建议**不是硬规则：一个极简的几何标志用 0.45 也说得通。
     *    所以它返回的是"要不要看一眼"，不是"合不合规"。
     */
    fun fillRatioLooksRight(ratio: Double): Boolean = ratio in 0.5..0.85
}
