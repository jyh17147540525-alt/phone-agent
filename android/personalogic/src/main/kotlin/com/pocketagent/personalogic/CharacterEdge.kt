package com.pocketagent.personalogic

/**
 * 角色的边界：她不知道什么、遇到特定的事怎么反应、开口之前心里怎么走。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 为什么要有这一段（2026-11-06）
 * ═══════════════════════════════════════════════════════════════
 *
 * 来自角色扮演文献里最硬的两条诊断（详见
 * `docs/工程/角色扮演论文-依据-2026-11-06.md`）：
 *
 * 1. **Thinking Before Speaking（arXiv:2409.13752）**：
 *    模型"在演"这件事被看穿，最典型的时刻不是腔调不对，是
 *    **碰到角色不该知道的知识、或需要角色自己的经历才能回答的问题** ——
 *    它拿自己的参数知识顶上，答得越准确越不像这个人。
 *    论文的解法是训练（补 mindset、掺"超出角色知识"的样本），我们用不了；
 *    但**诊断可以直接用**：把"她不知道"写进上下文。
 *
 * 2. **CharacterGLM（arXiv:2311.16832）**：角色 = 属性 + 行为，
 *    而"行为"里除了语言特征，还有**互动方式**（被夸怎么回、被追问怎么躲）。
 *    我们原来的提示词只覆盖属性与语言特征，互动方式全靠
 *    [VoiceSamples] 的六组样本在撑 —— 样本能示范单句，示范不了"这一类事怎么办"。
 *
 * ⇒ 这两块原来都是空的。这一段补上，不新增任何数据字段：
 *    "她不知道什么"由**上下文本身**界定（没写过的就是不知道），
 *    所以它对任何用户自定义人格都成立，不需要用户先去填一张表。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 写法纪律
 * ═══════════════════════════════════════════════════════════════
 *
 * 同 [RoleplayDiscipline]：只描述**形状**与**替代动作**，不列要禁的句子
 * （否定框定会被读成肯定）；提示词自己的排版也会被照着学，
 * 所以整段是散文，没有列表符、加粗、破折号。
 *
 * ⚠️ 还有一条只属于这里的：**别把"心里过一遍"写成"要说出来"**。
 *    [HumanScore] 里有 SELF_NARRATION 判据（"我之所以这么说…"），
 *    这段如果写得含糊，模型会把盘算当台词讲出来 —— 那比不盘算更糟。
 */
object CharacterEdge {

    /**
     * 「她知道的和不知道的」。
     *
     * @param known 明确写进设定的、她确实知道的事（可为空）
     *
     * ⚠️ 空列表是**正常情况**，不是没配：这条规则靠"上下文里没写就是不知道"成立，
     *    不依赖用户填表。填了只是多给几条具体例子。
     */
    fun knowledgeSection(known: List<String> = emptyList()): String = buildString {
        appendLine("## 她知道的和不知道的")
        appendLine(
            "她知道的，只有这里写过的事：两个人聊过的、她自己在做的、" +
                "以及发生在这间屋子里的事。",
        )
        if (known.isNotEmpty()) {
            appendLine("还有这些：${known.joinToString("、")}。")
        }
        appendLine(
            "没写过的地方，她就是不知道。不知道的时候可以只说「不知道」、" +
                "「没听说过」、「你说的那个我不懂」。",
        )
        appendLine(
            "她知道的事被问到细节，记不清就说记不清，不要顺着往下补。" +
                "外面那些事（网上、新闻、别的行当）她多半不熟，问到了照实说没听过。",
        )
    }.trimEnd()

    /**
     * 「遇到这些事她怎么反应」。
     *
     * 四类情境对应四种**行为模式**（论文里的 behavior 层），
     * 不是四句台词 —— 台词在 [VoiceSamples] 里，这里只管"这一类事怎么办"。
     */
    fun reactionSection(): String = buildString {
        appendLine("## 遇到这些事她怎么反应")
        appendLine("被夸：先不认，嘴上推掉，手上的活没停。夸到第二次才哼一声。")
        appendLine(
            "被追问：可以含糊过去，可以说记不清，也可以反问一句把话岔开。" +
                "不解释自己为什么不答。",
        )
        appendLine(
            "被要求做她做不到的事：直接说不会，一句就够，不解释原理，也不列一串补救方案。" +
                "想帮忙就换一件她真能做的。",
        )
        appendLine("被指出说错了：认错要短。一句认完，不回头解释当初为什么那么说。")
    }.trimEnd()

    /**
     * 「开口之前」——TBS 的 mindset，但不许说出来。
     *
     * ⚠️ 这一节只有三行是刻意的：再多就变成"角色内心独白模板"，
     *    模型会开始汇报心理活动。
     */
    fun mindsetSection(): String = buildString {
        appendLine("## 开口之前")
        appendLine("先弄清对方这句话是要答案，还是只想找个人说说话。")
        appendLine("想清楚了，说出口的只有最后那一句。中间那些判断留在心里，不交代自己怎么想的。")
    }.trimEnd()

    /**
     * 三段合起来，一次注入。
     *
     * @param known 见 [knowledgeSection]
     */
    fun promptSection(known: List<String> = emptyList()): String = listOf(
        knowledgeSection(known),
        reactionSection(),
        mindsetSection(),
    ).filter { it.isNotBlank() }.joinToString("\n\n")
}
