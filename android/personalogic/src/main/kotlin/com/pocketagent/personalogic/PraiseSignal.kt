package com.pocketagent.personalogic

/**
 * **认可的检测** —— 用户这句话是不是在夸 / 在谢。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★★ 2026-11-02：为什么需要一个"检测器"而不是让模型判断
 * ═══════════════════════════════════════════════════════════════
 *
 * 激素要真的动起来，就必须有事件源。而事件源里最容易拿到的两个是：
 *
 * | 事件 | 来源 |
 * |---|---|
 * | 争执 / 不满 | **已有** `legacy/FrictionLevel.of(text)` |
 * | 久别重逢 | **已有** 上一轮的时间戳 |
 * | 认可 / 被夸 | ❗ 没有 |
 *
 * ⇒ 补这一个。它是**纯文本启发式**，与 `Humanizer` / `RefusalDetector`
 *   同一路数：宁可漏，不要误判。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 判据刻意保守：三种情况**都不算**认可
 * ═══════════════════════════════════════════════════════════════
 *
 * 1. **问句**："你好吗？""这样对吗？" —— 那是提问，不是夸。
 *    （判据：含 `？`/`?` 且不是感叹句）
 * 2. **否定式**："不太好""不怎么样" —— 含否定词就直接不算。
 *    宁可漏一次夸奖，也不能把抱怨读成夸奖 —— 那会让激素往反方向动，
 *    表现为"被骂了反而更高兴"，是明显的失真。
 * 3. **只是礼貌**："谢谢" 单独出现算弱信号，需要额外的肯定词才算强。
 *
 * ★ 这一点与 `FrictionLevel` 的设计取向相反：那边**宁重不轻**
 *   （吵架要吵起来才有戏），这边**宁漏不误**（认错夸奖会让角色变得谄媚）。
 */
object PraiseSignal {

    /** 强信号 —— 出现任意一个就算。 */
    private val STRONG = listOf(
        "你真好", "真好", "太好了", "太棒", "好厉害", "厉害",
        "喜欢你", "爱你", "谢谢你", "谢谢",
        "说得对", "说得太对", "有道理", "你说得没错",
        "舒服多了", "好多了", "帮我大忙", "帮了大忙",
        "离不开你", "有你真好", "你最懂", "懂我",
        "可爱", "温柔", "贴心", "靠谱",
    )

    /** 否定词 —— 出现任意一个就**整体判否**。 */
    private val NEGATORS = listOf(
        "不", "别", "没", "甭", "莫",
    )

    /** 疑问标记 —— 问句里的"好""对"通常是提问，不是夸。 */
    private val QUESTION_MARKS = listOf("？", "?", "吗", "呢")

    /**
     * 这句话是不是在认可。
     *
     * @return true = 值得给一次 [HormoneEvent.Praise]
     */
    fun isPraise(userSaid: String): Boolean {
        val t = userSaid.trim()
        if (t.isEmpty()) return false

        // ① 必须先命中强信号
        val hit = STRONG.firstOrNull { t.contains(it) } ?: return false

        // ② 问句不算 —— 但要放行"谢谢你！"这类感叹
        val looksQuestion = QUESTION_MARKS.any { t.contains(it) }
        if (looksQuestion) return false

        // ③ 否定词：**只看信号词附近**，不是整句。
        //
        // ⚠️ 为什么不能看整句：`"不太好，但谢谢你"` 里那个"不"属于前半句，
        //    而"谢谢你"是明确的认可。一刀切会把整句判否。
        // ⇒ 只看信号词前两个字以内有没有否定词。
        val at = t.indexOf(hit)
        val before = if (at <= 2) t.take(at) else t.substring(at - 2, at)
        if (NEGATORS.any { before.contains(it) }) return false

        return true
    }
}
