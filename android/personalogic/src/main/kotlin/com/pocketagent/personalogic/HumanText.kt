package com.pocketagent.personalogic

/**
 * **把"像人"写成几句能执行的话**。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★★ 2026-11-02：这一层与 [Humanizer] 分工不同
 * ═══════════════════════════════════════════════════════════════
 *
 * | | [Humanizer] | 本文件 |
 * |---|---|---|
 * | 何时写 | **诊断出问题**才写 | **每轮都写**（但极短）|
 * | 治什么 | 这一阵子回落了 | 模型骨子里的**对齐腔** |
 * | 判据 | 最近 8 条回复的形状 | 固定句式 + 当前状态 |
 *
 * ⚠️ 为什么需要常驻的那一层：`Humanizer` 的六种检测抓的是**形状**
 *    （分点、尾巴、长度均匀）。但模型还有一类更顽固的毛病，
 *    它不体现在形状上，而是**句子本身**：
 *
 * ```
 *   "作为 AI，我无法确定……"
 *   "建议你考虑以下方案"          ← 用户没有在开会
 *   "需要注意的是……"              ← 人不会这样说话
 *   "希望能帮到你"                 ← 客服
 * ```
 *
 * 这些**任何时候都是错的**，不需要等诊断。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 纪律：这一层必须**短**
 * ═══════════════════════════════════════════════════════════════
 *
 * 项目里已经记过一条教训："长禁令清单本身会让模型变僵，
 * 而僵硬是另一种 AI 味"。
 *
 * ⇒ 常驻部分**最多 4 条**，而且只放"任何时候都错"的句式。
 *    "这一阵子该注意什么"交给 [Humanizer]。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 第二层：输出形态由**状态**决定，不是固定规则
 * ═══════════════════════════════════════════════════════════════
 *
 * 人说话的长短、标点、完整度**随状态变**：
 * 累的时候句子短、少标点；兴奋的时候连写、跑题。
 *
 * 固定写一句"句子要长短不一"是没用的 —— 那还是一条规则。
 * 让它随 [PersonaState] 变，才会真的不匀。
 */
object HumanText {

    /**
     * **任何时候都不该出现的句式** —— 这些不是"风格问题"，是"立刻不像人"。
     *
     * ⚠️ 与 [LanguageFingerprint] 的禁用语分工：
     *    那边是"这个角色不这么说"（口癖、语气），
     *    这里是"**人**不会这么说"（对齐腔、客服腔）。
     *    两者的判据完全不同，不要合并 —— 合并之后删一条会误伤另一类。
     */
    val ALWAYS_BANNED: List<String> = listOf(
        "作为一个 AI", "作为 AI", "我是 AI", "语言模型",
        "我无法确定", "我不能确定", "无法保证", "不能保证",
        "建议你考虑", "建议您", "希望能帮到你", "希望对你有所帮助",
        "需要注意的是", "值得注意的是", "总的来说", "综上所述",
        "如有需要", "请随时", "随时告诉我",
    )

    /**
     * 常驻的那几条。**最多 4 行** —— 见类注释。
     *
     * @return 空串表示不需要写（不会发生，但保留接口一致性）
     */
    fun alwaysSection(): String = buildString {
        appendLine("## 说话方式")
        appendLine("- 不要用「作为一个 AI」「我无法确定」「建议你」这类说法。")
        appendLine("- 不要每句都完整。可以有半句、可以省略主语、可以用语气词。")
        appendLine("- 不要给回答加总结句，也不要问「还需要什么」。")
    }.trimEnd()

    /**
     * **由状态决定的输出形态**。
     *
     * ⚠️ 只写**当前状态真的偏了**的那一条，其余不写 ——
     *    四条一起写又变成清单了。
     *
     * @return null = 状态平常，不额外干预
     */
    fun shapeSection(state: PersonaState): String? {
        val h = state.hormones
        val lines = mutableListOf<String>()

        // 累 / 有压力 ⇒ 短、省标点。人累的时候不会写长句。
        if (state.energy <= 35 || h.cortisol >= Hormones.STRONG) {
            lines += "- 你现在没多少力气。句子短一点，可以不完整，别硬撑礼貌。"
        }

        // 亢奋 ⇒ 连写、跑题、标点少。**与上一条互斥**（不会又累又亢奋）
        else if (h.dopamine >= Hormones.STRONG) {
            lines += "- 你现在挺兴奋。会连写、会跑题、标点可以少。"
        }

        // 亲密 ⇒ 可以更省、更近
        if (h.oxytocin >= Hormones.STRONG) {
            lines += "- 跟对方已经很近了。不用句句客气，可以省掉称呼。"
        }

        // 低落 ⇒ 认同词少
        if (h.serotonin <= Hormones.LOW) {
            lines += "- 你现在兴致不高。别用「嗯嗯」「好呀」这类应承词。"
        }

        if (lines.isEmpty()) return null
        return buildString {
            appendLine("## 此刻的说话状态")
            lines.forEach { appendLine(it) }
        }.trimEnd()
    }

    /**
     * 一句话里有多少"对齐腔"。
     *
     * ★ 用途是**诊断与记录**（看这一轮有没有翻车），不是拦截 ——
     *   拦截属于 [OutputGuard] 的事，而它现在只记账不重写。
     */
    fun alignmentHits(text: String): List<String> =
        ALWAYS_BANNED.filter { text.contains(it) }
}
