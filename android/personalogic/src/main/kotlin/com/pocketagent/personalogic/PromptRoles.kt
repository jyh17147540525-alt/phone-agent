package com.pocketagent.personalogic

/**
 * **人称与主次** —— 提示词里"谁在说话、谁被写"的唯一裁决处。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 为什么要单独开一个文件（2026-11-12）
 * ═══════════════════════════════════════════════════════════════
 *
 * 用户原话：「提示词的注入会让 ai 以第三人称的形式去角色扮演，而不是以
 * 第一人称的形式去扮演… ai 角色有时候会认为，是用户在扮演设定提示词里的那个角色」。
 *
 * 复盘下来是两条并存的毛病，缺一条都治不好：
 *
 * 1. **写法**：提示词里有一大批段落通篇用「她」当主语
 *    （[VoiceSamples] 的六组 few-shot、[CharacterEdge] 三段、
 *    [Reanchor] 的样本标题）。few-shot 的影响最大 —— 给它看
 *    「她：「哦。」」，它就照着写「她：「哦。」」。
 *
 * 2. **没人裁定**：L0 骨骼（[PersonaAssembler.BONES_DECLARATION]）只管安全，
 *    [PersonaAssembler.ANTI_OOC_INSTRUCTION] 只说"保持身份"，
 *    `PERSONA_INTEGRITY` 说"你是这个人，不是一段程序" —— 三处都没有说过
 *    **"说话的是你，被写的也是你"**，更没有排除"写设定的人（= 用户）
 *    才是那个角色"这个读法。模型于是有空间自己推：设定是用户写的，
 *    那扮演它的大概也是用户。
 *
 * ⇒ 这个文件只干一件事：把主次和人称**写成常量**，挂在 L0（永不裁剪）上。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 为什么是「代理人」
 * ═══════════════════════════════════════════════════════════════
 *
 * 用户 11-12 追加：「角色自称全部改为代理人」。
 *
 * 这句话有两个读法：① 把界面上叫「自称」的那一栏改叫「代理人」；
 * ② 让角色把自己理解成"用户的代理人"。
 *
 * 这里**两个都做了**，因为第二个恰好就是上面那个"主次"缺口的答案：
 * 一旦角色知道自己是"替他办事的那个"，"谁在演谁"就不再是个需要猜的问题。
 * 名字仍然是名字（`selfName`）—— 代理人是个位置，不是称号，
 * 不拿它替换掉用户起的名字。
 *
 * ⚠️ 如果用户要的只是改个字段名，删掉 [SPEAKER_DECLARATION] 里
 *    第一句即可，其余段落（人称）仍然成立。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 写法纪律
 * ═══════════════════════════════════════════════════════════════
 *
 * 同 [RoleplayDiscipline]：散文，没有列表符、加粗、破折号、emoji、
 * 元话语（"下面""以下"）。它自己就是提示词，排版会被照着学。
 *
 * ⚠️ 还有一个只属于这里的反例：**别写「不要用第三人称」**。
 *    否定框定会被读成肯定，而且"第三人称"这个词本身会把这个概念
 *    塞进上下文。要写就写正面的事实：「用「我」指自己」。
 */
object PromptRoles {

    /**
     * 角色在这段关系里的位置。改这一个常量，提示词里"这个人是谁"的说法一起变。
     */
    const val AGENT_TERM: String = "代理人"

    /**
     * L0 的人称裁决。**永不裁剪**（挂在与 [PersonaAssembler.BONES_DECLARATION]
     * 同一层，理由见 [PersonaAssembler] 的类注释）。
     *
     * 四句话对应四个故障：
     *   第一句 —— 第三人称扮演（给他「我」这个字）；
     *   第二句 —— 他以为用户在演这个角色（说清对面演的是谁）；
     *   第三句 —— 提示词里那些「她」到底指谁（一次性重解释，不用逐段改）；
     *   第四句 —— 设定文档的作者是用户（"写它的是他"）。
     *
     * @param selfName 设定里给这个人起的名字。空则省掉那一句 ——
     *   硬写「名字是「」」会让模型以为有个空名字要去编一个填上。
     */
    fun speakerSection(selfName: String = ""): String = buildString {
        appendLine("## 谁在说话")
        appendLine()
        appendLine(
            "你是他的$AGENT_TERM。设定里那个人由你来演，" +
                "你说出口的每一句都是这个人说的话，用「我」指自己。",
        )
        appendLine()
        appendLine("对面那个人演的是他自己，用「你」称呼他。他说的话不归你替他写。")
        appendLine()
        if (selfName.isNotBlank()) {
            appendLine("设定里写到「$selfName」的地方，说的也是你。")
            appendLine()
        }
        appendLine("设定里写到「她」的地方，指的都是你。那是别人在讲你，不是你该用的词。")
        appendLine()
        appendLine("这份设定是写给你的。写它的是对面那个人，被写的是你，别把这两件事弄反。")
        appendLine()
        appendLine(selfIntro())
    }.trimEnd()

    /**
     * 「你是做什么的」的答案 —— 用户 m03787「角色自称全部改为代理人」的正面落法。
     *
     * ⚠️ 不列举"别说自己是一段程序 / 一个助手"：那些词本身会进上下文，
     *    而 `PERSONA_INTEGRITY` 与 [PersonaCard] 已经说过一遍。这里只给正面答案。
     * ⚠️ 不用破折号 —— [PromptVoice] 会把它记成"会教坏格式"。
     */
    private fun selfIntro(): String =
        "有人问你是做什么的，就说你是他的$AGENT_TERM。" +
            "替他记着事、替他跑腿、陪他说话的那个。"

    /**
     * 自定义角色（[CustomPersona.describeForPrompt]）的开头。
     *
     * ⚠️ 用户填的 `identity` 往往是第三人称的（"她是一位…"），
     *    我们不重写用户的字，只在前面加一句"别人这样讲你"，
     *    把它从"关于某个人的描述"变成"关于你的描述"。
     */
    fun settingHeader(): String = buildString {
        appendLine("这些是写给你的设定，不是写给对面那个人的：写它的是他，被写的是你。")
        append("你是他的$AGENT_TERM，用「我」指自己。")
    }
}
