package com.pocketagent.personalogic

/**
 * **激素系统的文献参数表** —— 每个数字的出处，以及它被怎么映射进 0..100。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 先说清楚一件事：我们建模的不是"血浆浓度"
 * ═══════════════════════════════════════════════════════════════
 *
 * 人是"神经递质 + 内分泌"两层：
 *
 * | 层 | 时间尺度 | 例子 |
 * |---|---|---|
 * | 神经递质（相位） | 毫秒–秒 | 多巴胺 burst、去甲肾上腺素放电 |
 * | 神经递质（紧张） | 秒–分钟 | 蓝斑紧张性放电、5-HT 释放 |
 * | 内分泌（激素） | 分钟–小时 | 皮质醇、催产素、睾酮 |
 *
 * 我们的 `Hormones` 是**行为状态**，不是血检报告：它要回答"这条消息该怎么回"，
 * 而不是"现在血清里有多少 nmol/L"。所以：
 *
 * · **能直接用的**（皮质醇、催产素的时程；血清素周转；昼夜节律）就用文献数值；
 * · **不能直接用的**（多巴胺/血清素的中枢活动无法从外周血推断）只用**机制方向**，
 *   时间常数取"行为余韵"，并在此标明它是产品量而不是生理量。
 *
 * 把这两类分开写，比假装每个数都有 DOI 更有用 —— 后来改这块的人不会
 * 因为一句"文献说的"就不敢动。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 一条贯穿全部的依据：**激素有昼夜节律，且应激反应叠在节律上**
 * ═══════════════════════════════════════════════════════════════
 *
 * 皮质醇的日间形状（血清，nmol/L）：
 *
 * ```
 *   00:00–02:00  谷   ~50–140      （低于检测下限到 140）
 *   08:00–09:00  峰   ~300–700     （均值约 460 ± 235）
 *   16:00–17:00  降   ~150–300
 * ```
 *
 * 出处：Ljubijankić 2008（唾液与血清同步测定，PMC5698338）；
 * Medscape 实验室参考（8–9 点 >300 nmol/L 排除肾上腺皮质功能不全）；
 * Adam 2017 综述（昼夜斜率与健康的系统回顾，PMC5568897）。
 *
 * ⚠️ 我们**不**把这条曲线直接加到 [Hormones.cortisol] 上。理由：
 *    晨峰是"正常的生理高峰"，不是"她现在很紧张"。把基线画到脸上，
 *    会导致角色每天早上都"有点紧绷" —— 那是错的。
 *    真实作用是：**同样的刺激，夜里反应更小**（HPA 轴在谷值时反应性低）。
 *    见 [cortisolReactivity]。
 */
object HormoneKinetics {

    // ═══════════════════════════════════════════════════════════
    //  皮质醇（HPA 轴终产物）
    // ═══════════════════════════════════════════════════════════

    /**
     * 内源性皮质醇的**血浆半衰期**：66 分钟（正常激素水平下）。
     *
     * ⚠️ 大剂量时会延长（结合球蛋白饱和），我们不需要那一支。
     * 出处：Holland-Frei《Pharmacokinetics of Corticosteroids》
     * <https://www.ncbi.nlm.nih.gov/books/NBK13300/>
     */
    const val CORTISOL_PLASMA_HALF_LIFE_MINUTES = 66.0

    /**
     * 心理应激后皮质醇**峰值出现在 20–30 分钟**。
     *
     * 经典 Trier Social Stress Test（公开演讲 + 心算）的时程：
     * 上升 10–20 min，峰值 20–30 min，60–90 min 回到基线。
     * 出处：Kirschbaum, Pirke & Hellhammer 1993, Neuropsychobiology
     * <https://doi.org/10.1159/000119004>
     */
    const val STRESS_PEAK_MINUTES_MIN = 20.0
    const val STRESS_PEAK_MINUTES_MAX = 30.0

    /** 应激后回到基线的时间窗：60–90 分钟（同一出处）。 */
    const val STRESS_RECOVERY_MINUTES_MIN = 60.0
    const val STRESS_RECOVERY_MINUTES_MAX = 90.0

    /**
     * **皮质醇觉醒反应**（CAR）：醒后 30–45 分钟出现，平均升高 50–60%。
     *
     * 我们**没有"醒来"这个事件**（角色的"醒"就是用户来找它），
     * 所以这条只作为"晨间反应性更高"的旁证，不单独建模。
     * 出处：Adam et al. 2017, Psychoneuroendocrinology 综述
     * <https://pmc.ncbi.nlm.nih.gov/articles/PMC5568897/>
     */
    const val CAR_WINDOW_MINUTES_MIN = 30.0
    const val CAR_WINDOW_MINUTES_MAX = 45.0
    const val CAR_RISE_FRACTION = 0.55

    /** 血清皮质醇参考上限/下限（8–9 点 / 深夜），仅用于说明量级。 */
    const val SERUM_CORTISOL_MORNING_NMOL_L = 460.0
    const val SERUM_CORTISOL_NIGHT_NMOL_L = 140.0

    /**
     * **HPA 轴的负反馈强度**：皮质醇越高，回落越快。
     *
     * 机制：糖皮质激素受体（GR）介导的负反馈抑制 CRH/ACTH，外加肝脏清除加快。
     * 这在数学上表现为"高压时有效半衰期变短"，见 `HormoneEngine.advance`。
     *
     * ⚠️ 0.6 是**产品标定**（让 100 分时的有效半衰期约为基线的 0.62 倍）。
     *    文献能给的只有方向（负反馈存在、时滞 30–60 min），给不了这个系数。
     */
    const val HPA_NEGATIVE_FEEDBACK_GAIN = 0.6

    /**
     * 夜间（22:00–06:00）的**应激反应性系数**。
     *
     * 依据：HPA 轴在昼夜谷值时对急性刺激的反应幅度更小
     * （皮质醇分泌能力本身随时钟变化，凌晨最低）。
     * ⚠️ 这是**方向性**依据，系数是标定值；白天一律 1.0，不区分上午下午
     *    （那一层证据互相矛盾，见 Kudielka 等关于"上午 vs 下午 TSST"的争议）。
     */
    const val NIGHT_STRESS_REACTIVITY = 0.85

    // ═══════════════════════════════════════════════════════════
    //  催产素（神经肽，不是类固醇）
    // ═══════════════════════════════════════════════════════════

    /**
     * 催产素的**血浆半衰期只有 3–6 分钟**（静脉给药，多数报告 1–6 min）。
     *
     * 出处：Uvnäs-Moberg 等 2024, Am J Obstet Gynecol 综述
     * <https://doi.org/10.1016/j.ajog.2024.02.024>
     *
     * ⚠️ 这看起来和我们表的"45 分钟"矛盾 —— 不矛盾，见下一条。
     */
    const val OXYTOCIN_PLASMA_HALF_LIFE_MINUTES = 4.5

    /**
     * 我们用的**行为半衰期：45 分钟**。
     *
     * 依据：血浆里的催产素几分钟就清了，但**受体后信号**（G 蛋白耦联、
     * 突触可塑性）持续得更久。鼻喷催产素的行为效应在给药后 30–60 分钟
     * 最明显，且常持续 1 小时以上。
     *
     * ⚠️ 所以 [HormonePolicy.oxytocinHalfLifeHours] 描述的是"亲近感的余韵"，
     *    不是"血里还剩多少"。这也是为什么旧的 24 小时太长：
     *    它让一次拥抱影响一整天，而真实的余韵是"半小时内格外黏"。
     */
    const val OXYTOCIN_BEHAVIOR_HALF_LIFE_MINUTES = 45.0

    /**
     * 抚摸要**持续约 20 秒**才明显触发催产素释放（"20 秒拥抱"）。
     *
     * 出处：多项 hugs/oxytocin 研究（如 UCLA Health 的科普综述；
     * Romney 等 2023 关于拥抱与 CAR 的研究）。
     * ⚠️ 我们的一条消息无法测"持续几秒"，所以这一条只用于**文案与判断**：
     *    短促的"抱一下"和长篇的亲近叙述给同样的 +14 是不精确的，
     *    但比按字数算更不容易被钻空子。
     */
    const val TOUCH_THRESHOLD_SECONDS = 20.0

    // ═══════════════════════════════════════════════════════════
    //  多巴胺（相位信号，不能当血浓度用）
    // ═══════════════════════════════════════════════════════════

    /**
     * 多巴胺神经元的**相位性 burst 潜伏期约 100–200 ms**，
     * 编码奖励预测误差（RPE）：好于预期 → burst；差于预期 → dip。
     *
     * 出处：Schultz 2016, Nat Rev Neurosci《Dopamine reward prediction-error
     * signalling: a two-component response》
     * <https://pmc.ncbi.nlm.nih.gov/articles/PMC5549862/>
     *
     * ⚠️ 我们不能建模秒级信号：一次交互的粒度是"一条消息"（十几秒到几分钟）。
     *    所以 [HormonePolicy.dopamineHalfLifeHours] = 30 分钟，是**行为余韵**：
     *    "被夸之后半小时内明显高兴"。这是产品量，不是生理量。
     */
    const val DOPAMINE_PHASIC_LATENCY_MS = 150.0
    const val DOPAMINE_BEHAVIOR_HALF_LIFE_MINUTES = 30.0

    // ═══════════════════════════════════════════════════════════
    //  血清素（慢变量）
    // ═══════════════════════════════════════════════════════════

    /**
     * 急性色氨酸耗竭（ATD）实验给出的**周转时间尺度**：
     * 耗竭 5–7 小时后情绪开始下降，24 小时后恢复。
     *
     * 出处：Klaassen 1999（24 小时耗竭，6 小时时情绪最低，24 小时检测不到）
     * <https://pubmed.ncbi.nlm.nih.gov/10459398/>
     *
     * ⚠️ 这是一条**弱效应**：ATD 在健康人身上只让情绪轻微下降，
     *    效应量小且个体差异大。所以我们把它设成"慢变量"（6 小时半衰期），
     *    而不是"一次争执就血清素崩"。方向对，幅度克制。
     */
    const val SEROTONIN_TURNOVER_HOURS_MIN = 5.0
    const val SEROTONIN_TURNOVER_HOURS_MAX = 7.0
    const val SEROTONIN_BEHAVIOR_HALF_LIFE_HOURS = 6.0

    // ═══════════════════════════════════════════════════════════
    //  社会支持对压力反应的缓冲
    // ═══════════════════════════════════════════════════════════

    /**
     * 社会支持降低皮质醇反应的**元分析效应量**（Cohen's d = 0.83）。
     *
     * Thorsteinsson & James 1999 汇总 22 项实验研究、26 组比较、56 个效应量：
     * 心率/SBP d = 0.61、DBP d = 0.51、皮肤电 d = 0.25、**皮质醇 d = 0.83**。
     * 也就是说，在实验室应激里，「有人在旁边支持」对皮质醇的影响
     * 反而是这几个指标中**最大**的一个 —— 比心血管反应还大。
     * <https://doi.org/10.1080/08870449908407353>
     *
     * ⚠️ 方向要读准：元分析比较的是「有支持 vs 无支持」两组，
     *    不是「支持强度线性降低反应」。它支持的是"这一条该有，而且不小"，
     *    不支持"每一分亲近值降低多少 nmol/L"。
     */
    const val SOCIAL_SUPPORT_CORTISOL_EFFECT_SIZE_D = 0.83

    /**
     * 把 d = 0.83 折成增益系数：**0.75**。
     *
     * 折法写在明处（别当实测值）：大效应量大致对应"一个标准差左右"的组间差，
     * 落到"反应幅度"上约等于打七折多。取 0.75 是个整齐、可解释的数。
     *
     * ⚠️ 这是**产品标定**。文献支持"该有这一条，而且不小"，
     *    支持不了"就是 0.75"。
     */
    const val SOCIAL_SUPPORT_CORTISOL_GAIN = 0.75

    /**
     * 机制解释（为什么催产素能压低皮质醇反应）：催产素能神经元对下丘脑
     * CRH 神经元有**抑制**性输入，社会接触释放的催产素因此可以直接
     * 掐住 HPA 轴的最上游。
     *
     * 出处：Endogenous oxytocin inhibits hypothalamic stress CRH neurons
     * <https://www.biorxiv.org/content/10.1101/543165v1.full-text>
     *
     * ⚠️ 这是**动物电生理**证据，人类身上只有上面那条行为层面的元分析。
     *    写在这里是为了解释"这条互锁为什么该存在"，
     *    不是拿来定数值的 —— 别把机制写成了参数。
     */

    // ═══════════════════════════════════════════════════════════
    //  我们**没有**建模的几条（写在这里防止后来者以为漏了）
    // ═══════════════════════════════════════════════════════════

    /**
     * 去甲肾上腺素 / 肾上腺素：血浆半衰期 2–3.5 分钟，管"当下这一秒的警觉"。
     * 我们的最小时间粒度是"一条消息"，秒级信号没有落点；
     * 它要表达的东西（急性警觉、心跳快）与 [Hormones.cortisol] 的效果重叠。
     *
     * 出处：Abboud 等 2009（肾上腺素在感染性休克患者中的 t1/2 = 3.5 min）
     * <https://doi.org/10.1186/cc7972>
     */
    const val NOREPINEPHRINE_HALF_LIFE_MINUTES = 2.0

    /**
     * 褪黑素：半衰期 40–50 分钟，夜间分泌，**光照即可抑制**
     * （室内光 <500 lux 就够，甚至 <30 lux 也有影响）。
     *
     * 我们不建模它，因为它的行为输出（困）已经由 [PhysiologyEngine] 的
     * 昼夜节律 + 睡眠债承担了 —— 再加一条会重复计分。
     * 需要"她注意到天黑了"时，走时间判断，不要伪造一个激素。
     */
    const val MELATONIN_HALF_LIFE_MINUTES = 45.0

    /**
     * 睾酮：竞争后 15–36 分钟升高（胜者）/ 降低（败者），半衰期约 70 分钟。
     *
     * 出处：Geniole 等 2017 元分析《Effects of competition outcome on testosterone》
     * <https://doi.org/10.1016/j.yhbeh.2017.01.006>
     *
     * 不建模的理由：我们没有"胜负"这个事件类型。硬造一个"她赢了"会变成
     * 设定里的竞争叙事，与"陪伴"的定位冲突。若将来做"游戏/比赛"场景再加。
     */
    const val TESTOSTERONE_HALF_LIFE_MINUTES = 70.0

    /**
     * **当下这一刻的应激反应性**（0.85–1.0）。
     *
     * 白天 1.0；22:00–06:00 平滑降到 [NIGHT_STRESS_REACTIVITY]。
     * 用于 `HormoneEngine.step` 里给皮质醇增益乘系数 —— 同样是"被凶一句"，
     * 凌晨两点的生理反应比上午十点小（HPA 轴在谷值）。
     *
     * ⚠️ 这是方向性校正，不是精确值。它的作用是让"深夜的争执"不至于
     *    和"白天的争执"一模一样，而不是宣称我们知道差多少。
     */
    fun stressReactivity(hourOfDay: Double): Double {
        val h = ((hourOfDay % 24.0) + 24.0) % 24.0
        // 22:00 → 1.0 线性降到 02:00 → 0.85，02:00–06:00 保持，06:00 回到 1.0
        val depth = when {
            h >= 22.0 -> (h - 22.0) / 4.0
            h < 2.0 -> (h + 2.0) / 4.0
            h < 6.0 -> 1.0
            h < 8.0 -> (8.0 - h) / 2.0
            else -> 0.0
        }.coerceIn(0.0, 1.0)
        return 1.0 - depth * (1.0 - NIGHT_STRESS_REACTIVITY)
    }
}
