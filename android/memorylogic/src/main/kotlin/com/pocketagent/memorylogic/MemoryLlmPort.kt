package com.pocketagent.memorylogic

/**
 * 记忆层需要 LLM 时的**唯一出口**。
 *
 * ═══════════════════════════════════════════════════════════════
 *  为什么必须是一个端口，而不是自己发请求
 * ═══════════════════════════════════════════════════════════════
 *
 * 这是架构不变量 2 的落地：**记忆层不得自行发网络请求**。
 *
 * 三条理由，按重要性排序：
 *
 * 1. **计量**（红线 §8.2-3）。助理的一切模型调用必须过 `GatewayCore`
 *    （路由 → 熔断 → 解密 → 转发 → 计量）。记忆层偷偷直连一次，
 *    这次消耗就不在任何预算里 —— 用户看到的"本月花了多少"是假的。
 * 2. **可测**。本模块要能进离线验证器，就不能有 `OkHttpClient`。
 *    注入端口之后，测试用 `{ prompt, _ -> "canned json" }` 就够了。
 * 3. **可换档位**。原子提取、场景归纳、画像蒸馏对模型质量的要求不同
 *    （成本 vs 质量，见未决项 U-3）。[Purpose] 就是让上层按用途选档位的抓手。
 */
fun interface MemoryLlmPort {

    /**
     * 一次补全。
     *
     * @param prompt 由记忆层自己组装（提示词是**纯逻辑**，可离线断言）。
     * @param purpose 用途 —— 决定上层的档位选择与计量归类。
     * @return 模型原始返回。⚠️ 可能带代码围栏、可能不合法，
     *   解析与校验的责任在调用方（见 [AtomExtractor]）。
     */
    fun complete(prompt: String, purpose: Purpose): String

    /** LLM 被用来做什么 —— 三层的用途互不相同，混在一个档位上会让成本失控。 */
    enum class Purpose(val label: String) {
        /** L1：从原始对话里提取原子记忆（本阶段已落地） */
        ATOM_EXTRACTION("原子记忆提取"),

        /** L2：按任务聚合场景（P5 落地） */
        SCENE_AGGREGATION("场景归纳"),

        /** L3：持续蒸馏用户画像（P5 落地，输出直接喂给 `:personalogic`） */
        PROFILE_DISTILLATION("画像蒸馏"),
    }
}