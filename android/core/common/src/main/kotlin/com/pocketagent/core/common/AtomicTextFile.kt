package com.pocketagent.core.common

import java.io.File
import java.util.UUID

/**
 * 原子写文本文件：**先写临时文件，再改名就位**。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 它守的是"半截文件"这一类故障，而这类故障的后果是静默的
 * ═══════════════════════════════════════════════════════════════
 *
 * 直接 `writeText` 覆盖一个已有文件时，进程可能在任何一刻消失
 * （系统回收、闪退、用户强停、电量耗尽）。那一刻文件里是**写了一半的内容**，
 * 而它**看起来是个正常的文件** —— 没有报错、没有痕迹。
 *
 * 具体到本项目：dsh 的 `settings.yaml` / 凭据文件被截断之后，
 * dsh 读到的是"能解析但内容不全"的 YAML，于是它按缺省值跑起来 ——
 * 表现是**行为诡异但完全说不出错在哪**，而用户唯一能想到的解释是
 * "是不是你们把 dsh 弄坏了"。
 *
 * `rename` 在同一文件系统内是原子的：外界要么看到旧内容，要么看到新内容，
 * 不存在中间态。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 为什么临时文件用**唯一名**而不是固定的 `xxx.tmp`
 * ═══════════════════════════════════════════════════════════════
 *
 * 固定名看起来更整洁（最多只留一个孤儿），但它有一个更糟的问题：
 * **两次并发写会共用同一个临时文件**，互相把对方的内容写坏，
 * 然后两个都"成功"改名就位 —— 结果是一个谁都没写出来的混合体。
 *
 * 唯一名的代价是崩溃会留下孤儿文件。所以这里在**失败路径上显式删除它**：
 * 只有"进程被硬杀"才会留下孤儿，而那正是无法避免的那一种。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 为什么放在 `:core:common` 而不是 `:app`
 * ═══════════════════════════════════════════════════════════════
 *
 * 它的失败形态是静默的，按项目纪律必须能被离线单测钉住。
 * `:core:common` 是纯 Kotlin 模块（`java.io.File` 是 JDK，不需要 Android），
 * 所以它进得了 `run_logic_tests.py` 的 `MODULES`；放 `:app` 则只能靠真机。
 */
object AtomicTextFile {

    /**
     * 把 [content] 写到 [target]。
     *
     * 父目录不存在会被创建（`dsh/` 这一层一开始并不存在）。
     *
     * @param onStaged **仅供测试**：临时文件已经写好、但**尚未改名就位**的那一刻回调。
     *
     *   ═══════════════════════════════════════════════════════════
     *   ⚠️ 为什么生产代码里会有一个测试专用的参数
     *   ═══════════════════════════════════════════════════════════
     *
     *   因为这个类**唯一的价值就是原子性**，而原子性从外部是看不见的：
     *   写完之后的最终状态，无论走不走临时文件都一模一样。
     *
     *   实测过：把实现换成 `target.writeText(content)`（整个临时文件机制删掉），
     *   **全部 959 个测试照过** —— 也就是说，任何后人"顺手简化"它都不会被发现。
     *   一个守不住自己唯一承诺的类，等于没有。
     *
     *   有了这个钩子，"此刻目标文件仍是旧内容"与"此刻临时文件已完整"这两条
     *   就都成了可断言的事实。与 `RoomUsageRecorder(dao, clock)` 的 `clock`
     *   是同一个手法：**为了让不可观测的性质变得可观测，接受一个测试接缝。**
     *
     * @return 是否成功。**刻意不抛异常** —— 调用链上没有任何人能处理它，
     *         而抛出去会让"配置没送达"这个**可解释的业务状态**变成崩溃。
     *         调用方要的是可以如实报告给用户的结果。
     */
    fun write(
        target: File,
        content: String,
        onStaged: (() -> Unit)? = null,
    ): Boolean {
        // 用绝对路径：相对路径的 `parentFile` 是 null，而 rename 也要求
        // 两边在同一文件系统上 —— 统一成绝对路径可以避免这两类意外。
        val abs = target.absoluteFile
        val parent = abs.parentFile ?: return false

        // 已存在但**不是目录**（比如同名文件挡在那里）→ 直接放弃。
        // 不放弃的话，后面的 writeText 会抛 IOException，虽然也会被吞成 false，
        // 但那时已经建了一个没用的临时文件。
        if (!parent.isDirectory && !parent.mkdirs()) return false

        val tmp = File(parent, "${abs.name}.tmp-${UUID.randomUUID().toString().take(8)}")

        return try {
            tmp.writeText(content)
            onStaged?.invoke()
            if (commit(tmp, abs)) {
                true
            } else {
                tmp.delete()
                false
            }
        } catch (e: Exception) {
            tmp.delete()
            false
        }
    }

    /**
     * 把临时文件改名就位。
     *
     * ⚠️ 先直接 rename。**失败时才**退到"删目标 + 再 rename" ——
     *    这一步不是原子的，所以不能作为默认路径。
     *    它存在的理由很具体：部分文件系统（Windows 尤其）上
     *    `rename` 到**已存在**的目标会失败，而"目标已存在"恰恰是
     *    配置投递的**常规**情况（第二次投递）。
     */
    private fun commit(tmp: File, target: File): Boolean {
        if (tmp.renameTo(target)) return true

        // 删除的结果不检查：目标不存在时 delete 返回 false，而那是完全正常的情形
        // （第一次投递），此时应当继续尝试 rename。
        target.delete()
        return tmp.renameTo(target)
    }
}
