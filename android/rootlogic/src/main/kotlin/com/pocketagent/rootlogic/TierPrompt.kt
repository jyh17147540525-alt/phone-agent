package com.pocketagent.rootlogic

/**
 * 把「这一趟有哪些手脚」写进系统提示词。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ★ 为什么需要这段话
 * ═══════════════════════════════════════════════════════════════
 *
 * 在它之前，模型对"自己现在能动什么"**完全没有信息**：它只看到工具清单，
 * 而工具清单在两种档位下是一样的（被挡的工具带着原因留在清单里）。
 * 于是它会在普通档里连点三次屏幕完成任务，用户那边手机一直在被抢 ——
 * 用户以为"这软件怎么老抢我手机"，而模型以为自己在正常干活。
 *
 * ⇒ 这段话只回答三件事：
 *   1. **我在哪一档**；
 *   2. **动屏幕会不会打断用户**（普通档会，root 档不会）；
 *   3. **现在哪几条路不通、通不了时该对用户说什么**（一句话，不列长清单）。
 *
 * ═══════════════════════════════════════════════════════════════
 *  ⚠️ 刻意写得很短
 * ═══════════════════════════════════════════════════════════════
 *
 * 关于"长提示词降低指令遵循"的证据是明确的（Instruction Stacking Collapse：
 * 24 条指令堆到 20 条时遵循率从 96% 掉到 20% 量级）。这段是**每轮都追加**的，
 * 所以它的预算按"三行"定，不是按"讲清楚"定 —— 讲清楚靠工具自己的报错文案。
 */
object TierPrompt {

    /** 提示词里最多列几条不通的路 —— 列全了会变成一张劝导表，模型会开始背它。 */
    private const val MAX_BLOCKED = 4

    /**
     * @return 空串 = 这一份计划没有任何值得提前说的（例如所有能力都通、且不占屏）
     */
    fun section(mode: PrivilegeMode, plan: TierPlan): String {
        if (plan.mounted.isEmpty() && plan.blocked.isEmpty()) return ""

        val where = when (mode) {
            PrivilegeMode.ROOT -> "你在 root 档：读屏与点按都不占用用户的屏幕，可以在后台把事情做完。"
            PrivilegeMode.NON_ROOT ->
                "你在普通档：读屏与点按会占用用户的屏幕 —— 任务期间用户不能正常用手机。" +
                    "所以一次能问清的不要拆成三次，能少动一下屏幕就少动一下。"
        }

        val blocked = plan.blocked.take(MAX_BLOCKED).map { "${it.tool}（${it.explain()}）" }

        return buildString {
            append("## 这一趟的手脚\n")
            append(where)
            if (blocked.isNotEmpty()) {
                append("\n现在这几条路不通：")
                append(blocked.joinToString("；"))
                append("。用户问起时，把上面括号里的「怎么开」原样转述给他 —— ")
                append("那是设置路径，不是猜测。")
            }
        }
    }
}
